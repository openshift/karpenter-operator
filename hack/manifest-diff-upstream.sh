#!/usr/bin/env bash
# Syncs or diffs operand RBAC from the OpenShift karpenter-provider-aws fork Helm
# chart, and Karpenter CRDs from the vendored provider modules, into pkg/assets/.
#
# CRDs come from vendor/ because each provider vendors wrapped core CRDs whose CEL
# rules restrict that provider's own label domains.
#
# When upstream adds new RBAC resources, this script fails and lists them. Add an
# `extract KIND NAME FILE` call below, then re-run.
#
# Usage (OPERAND_BRANCH is set by the Makefile, prefer `make manifest-diff[-sync]`):
#   hack/manifest-diff-upstream.sh          # diff only (exit 1 if out of sync)
#   hack/manifest-diff-upstream.sh --sync   # overwrite assets
#
# Requires: curl; helm, yq (auto-installed via `make manifest-diff-sync`)

set -euo pipefail

AWS_REPO_NAME="openshift/aws-karpenter-provider-aws"
OPERAND_BRANCH="${OPERAND_BRANCH:?set OPERAND_BRANCH or run via make}"

NAMESPACE="openshift-karpenter"

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CORE_DIR="${REPO_ROOT}/pkg/assets/karpenter"
AWS_DIR="${REPO_ROOT}/pkg/assets/aws"
AZURE_DIR="${REPO_ROOT}/pkg/assets/azure"
AWS_VENDOR_CRD_DIR="${REPO_ROOT}/vendor/github.com/aws/karpenter-provider-aws/pkg/apis/crds"
AZURE_VENDOR_CRD_DIR="${REPO_ROOT}/vendor/github.com/Azure/karpenter-provider-azure/pkg/apis/crds"
MODE="${1:-}"

YQ="${YQ:-yq}"
HELM="${HELM:-helm}"
for tool in curl "$YQ" "$HELM"; do
  command -v "$tool" &>/dev/null || { echo "ERROR: $tool not found" >&2; exit 1; }
done

tmpdir=$(mktemp -d)
trap 'rm -rf "$tmpdir"' EXIT

# --- Download & render -------------------------------------------------------
echo "==> Fetching ${AWS_REPO_NAME} @ ${OPERAND_BRANCH}..."
curl -sSL --retry 3 --retry-delay 2 "https://github.com/${AWS_REPO_NAME}/archive/refs/heads/${OPERAND_BRANCH}.tar.gz" | tar -xz -C "$tmpdir"
chart_dir=$(find "$tmpdir" -type d -name karpenter -path "*/charts/karpenter" 2>/dev/null | head -1)
[[ -n "$chart_dir" ]] || { echo "ERROR: failed to fetch chart" >&2; exit 1; }

echo "==> Rendering Helm chart..."
$HELM template karpenter "$chart_dir" \
  --namespace "$NAMESPACE" --skip-crds \
  --set "settings.clusterName=placeholder" \
  > "${tmpdir}/rendered.yaml"

# --- Extract resources --------------------------------------------------------
core_staging="${tmpdir}/core"
aws_staging="${tmpdir}/aws"
azure_staging="${tmpdir}/azure"
mkdir -p "$core_staging" "$aws_staging" "$azure_staging"

# Strip Helm-injected labels; keep functional ones like aggregate-to-admin.
strip='
  del(.metadata.labels["helm.sh/chart"]) |
  del(.metadata.labels["app.kubernetes.io/managed-by"]) |
  del(.metadata.labels["app.kubernetes.io/instance"]) |
  del(.metadata.labels["app.kubernetes.io/version"]) |
  del(.metadata.labels["app.kubernetes.io/name"]) |
  del(.metadata.annotations) |
  del(.metadata.labels | select(length == 0))
'

header="# DO NOT EDIT. Generated by hack/manifest-diff-upstream.sh from ${AWS_REPO_NAME} ${OPERAND_BRANCH}"

# extract KIND NAME FILE
# Pull exactly one document matching KIND/NAME from the rendered chart output,
# strip Helm metadata, and write it to FILE with a DO-NOT-EDIT header.
#   KIND  — Kubernetes resource kind (e.g. ClusterRole, RoleBinding)
#   NAME  — metadata.name to select from rendered chart
#   FILE  — output path to write the extracted document
extracted_names=""
extract() {
  local kind="$1" name="$2" file="$3"
  extracted_names+="${kind}/${name}"$'\n'
  local selected
  selected=$($YQ eval-all "select(.kind == \"$kind\" and .metadata.name == \"$name\")" "${tmpdir}/rendered.yaml")
  if [[ -z "$selected" ]]; then
    echo "ERROR: no document found for ${kind}/${name}" >&2
    exit 1
  fi
  printf '%s\n' "$header" > "$file"
  echo "$selected" | $YQ eval "$strip" - >> "$file"
}

echo "==> Extracting resources..."

# --- Core (cloud-agnostic, pkg/assets/karpenter/) ---
extract ClusterRole        karpenter-core  "${core_staging}/clusterrole-core.yaml"
extract ClusterRoleBinding karpenter-core  "${core_staging}/clusterrolebinding-core.yaml"
extract Role               karpenter       "${core_staging}/role.yaml"
extract RoleBinding        karpenter       "${core_staging}/role-binding.yaml"
extract Role               karpenter-dns   "${core_staging}/role-dns.yaml"
extract RoleBinding        karpenter-dns   "${core_staging}/role-binding-dns.yaml"

# Aggregate ClusterRole is CVO-managed (install/03_aggregate-clusterrole.yaml), not operator-reconciled.
# Mark it as handled so validation doesn't flag it.
extracted_names+="ClusterRole/karpenter-admin"$'\n'

# --- AWS (provider-specific, pkg/assets/aws/) ---
extract ClusterRole        karpenter "${aws_staging}/clusterrole.yaml"
extract ClusterRoleBinding karpenter "${aws_staging}/clusterrolebinding.yaml"

# --- Validate: no unhandled RBAC resources ------------------------------------
rendered_names=$($YQ eval '.kind + "/" + .metadata.name' "${tmpdir}/rendered.yaml" \
  | grep -E "^(Role|RoleBinding|ClusterRole|ClusterRoleBinding)/" | sort -u)

unhandled=$(comm -23 <(echo "$rendered_names") <(echo "$extracted_names" | sort -u))
if [[ -n "$unhandled" ]]; then
  echo "ERROR: upstream has RBAC resources not handled by this script:"
  echo "    ${unhandled//$'\n'/$'\n'    }"
  echo "  Add extract calls for them, then re-run."
  exit 1
fi

# --- Stage CRDs from vendor ----------------------------------------------------
crd_header="# DO NOT EDIT. Generated by hack/manifest-diff-upstream.sh"

for vendor_dir in "$AWS_VENDOR_CRD_DIR" "$AZURE_VENDOR_CRD_DIR"; do
  [[ -d "$vendor_dir" ]] || { echo "ERROR: missing vendored CRDs at ${vendor_dir#"${REPO_ROOT}"/}" >&2; exit 1; }
done

# stage_crds SRC_DIR DEST_DIR HEADER — copies SRC_DIR YAML into DEST_DIR with a DO-NOT-EDIT header.
stage_crds() {
  local src="$1" dest="$2" file_header="$3" f local_name
  for f in "${src}"/*.yaml; do
    [[ -f "$f" ]] || continue
    local_name="$(basename "$f")"
    printf '%s\n' "$file_header" > "${dest}/${local_name}"
    cat "$f" >> "${dest}/${local_name}"
  done
}

stage_crds "$AWS_VENDOR_CRD_DIR" "$aws_staging" "$crd_header"
stage_crds "$AZURE_VENDOR_CRD_DIR" "$azure_staging" "$crd_header"

# Apply OpenShift-specific schema adjustments before comparing or syncing assets.
aws_ec2_nodeclass_crd="${aws_staging}/karpenter.k8s.aws_ec2nodeclasses.yaml"
if [[ ! -f "$aws_ec2_nodeclass_crd" ]]; then
  echo "ERROR: upstream AWS EC2NodeClass CRD is missing" >&2
  exit 1
fi

# OpenShift-specific relaxations on upstream EC2NodeClass CRD:
# - only allow "Custom" amiFamily
# - only allow amiSelectorTerms using the "id" field
# - allow the "role" and "instanceProfile" to be missing as they are optional
"$YQ" eval '.spec.versions[0].schema.openAPIV3Schema.properties.spec.properties.amiFamily.enum = ["Custom"]' -i "$aws_ec2_nodeclass_crd"
"$YQ" eval '.spec.versions[0].schema.openAPIV3Schema.properties.spec.properties.amiSelectorTerms.x-kubernetes-validations = [{"message": "expected only \"id\" to be set", "rule": "self.all(x, has(x.id) && !has(x.alias) && !has(x.tags) && !has(x.name) && !has(x.owner) && !has(x.ssmParameter))"}]' -i "$aws_ec2_nodeclass_crd"
"$YQ" eval '.spec.versions[0].schema.openAPIV3Schema.properties.spec.x-kubernetes-validations = []' -i "$aws_ec2_nodeclass_crd"
"$YQ" eval ".spec.versions[0].schema.openAPIV3Schema.properties.spec.properties.role.\"x-kubernetes-validations\" = [{\"message\": \"role cannot be empty\", \"rule\": \"self != ''\"}]" -i "$aws_ec2_nodeclass_crd"

# --- Diff or sync -------------------------------------------------------------
# diff_dir EXPECTED ACTUAL [GLOB] [STRICT]
# Compare expected (upstream) files against actual (local) directory.
# Reports MISSING (expected has it, actual doesn't) and DIFF (content mismatch).
# In strict mode, also reports EXTRA (actual has it, expected doesn't).
# Returns non-zero on drift.
#   EXPECTED — directory with the reference files (e.g. freshly rendered from upstream)
#   ACTUAL   — local directory to compare against
#   GLOB     — shell glob restricting the EXTRA check in ACTUAL (default: *.yaml)
#   STRICT   — "true" (default) to flag EXTRA files in ACTUAL; "false" for one-way compare
diff_dir() {
  local expected="$1" actual="$2" glob="${3:-*.yaml}" strict="${4:-true}"
  local label="${actual#"${REPO_ROOT}"/}"
  local rc=0
  for f in "${expected}"/*.yaml; do
    [[ -f "$f" ]] || continue
    local base actual_file
    base=$(basename "$f")
    actual_file="${actual}/${base}"
    if [[ ! -f "$actual_file" ]]; then
      echo "MISSING: ${label}/${base}"; rc=1; continue
    fi
    local norm_up="${tmpdir}/u-${base}" norm_lo="${tmpdir}/l-${base}"
    grep -v '^[[:space:]]*#' "$f"           | $YQ eval '.' - > "$norm_up" 2>/dev/null || true
    grep -v '^[[:space:]]*#' "$actual_file" | $YQ eval '.' - > "$norm_lo" 2>/dev/null || true
    if ! diff -q "$norm_up" "$norm_lo" &>/dev/null; then
      echo "DIFF: ${label}/${base}"
      diff -u "$norm_up" "$norm_lo" --label "upstream/${base}" --label "local/${base}" || true
      rc=1
    fi
  done
  if [[ "$strict" == "true" ]]; then
    for f in "${actual}"/${glob}; do
      [[ -f "$f" ]] || continue
      [[ -f "${expected}/$(basename "$f")" ]] || { echo "EXTRA: ${label}/$(basename "$f")"; rc=1; }
    done
  fi
  return $rc
}

if [[ "$MODE" == "--sync" ]]; then
  mkdir -p "$CORE_DIR" "$AWS_DIR" "$AZURE_DIR"
  rm -f "${CORE_DIR}"/*.yaml
  cp "${core_staging}"/*.yaml "${CORE_DIR}/"
  rm -f "${AWS_DIR}"/*.yaml
  cp "${aws_staging}"/*.yaml "${AWS_DIR}/"
  rm -f "${AZURE_DIR}"/*.yaml
  cp "${azure_staging}"/*.yaml "${AZURE_DIR}/"
  echo "==> Synced. Review:"
  echo "      git diff pkg/assets/"
  exit 0
fi

echo "==> Comparing..."
exitcode=0
diff_dir "$core_staging" "$CORE_DIR" || exitcode=1
diff_dir "$aws_staging" "$AWS_DIR" || exitcode=1
diff_dir "$azure_staging" "$AZURE_DIR" || exitcode=1

if [[ $exitcode -eq 0 ]]; then
  echo "==> In sync with ${AWS_REPO_NAME} ${OPERAND_BRANCH}."
else
  echo "==> OUT OF SYNC. Run: hack/manifest-diff-upstream.sh --sync"
fi
exit $exitcode
